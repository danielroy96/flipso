/**
 * @file flipso_all.c
 * @brief The whole app as one translation unit, for the device build only.
 *
 * The sources stay one responsibility to a file; this is how the firmware
 * build compiles them. A .fap is linked relocatably (-Ur), which never merges
 * a string two object files share, and a call from one file to another is
 * never inlined, so splitting the app into files cost RAM once per file. As
 * one unit, a string is stored once and a small helper can be inlined
 * wherever it is used. Sharing one unit, a static name has to be unique
 * app-wide. The host builds still take the files one by one
 * (tools/test/sources.py), and tools/test/lint_sources.py fails when a source
 * is missing from the list below.
 *
 * flipso_calls.h comes first: it declares the firmware, then makes every call
 * declared after it - all of the app's own - a short one.
 */
